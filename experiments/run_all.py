#!/usr/bin/env python3
"""`make reproduce` (AGENTKV_SPEC.md Phase 6, §6.2): regenerates every
machine-generated figure and data file in `results/` from the committed
trajectories, in dependency order.

## Scope — stated plainly, not implied

This regenerates every DATA file (parquet), FIGURE (png), and machine-
generated stats `.md` that some experiment script's own `main()` writes to
disk (e.g. `phase1_gate1_summary.md`, `phase4_pareto_cost_summary.md`,
`phase6_cost_model_summary.md`). It does **not** regenerate the hand-
authored narrative documents that synthesize those numbers into prose —
`phase4_pareto_summary.md`, `phase6_demo_summary.md`, every top-level
`phaseN_summary.md`, `results/demo_deck/rehearsal.md`, and so on. Those are
written once by a person interpreting the numbers, not produced by any
script's `main()` — this project has never conflated the two even where
the names look similar (`phase4_kv_evict_summary.md` is auto-generated by
`phase4_kv_evict.py`; `phase4_hybrid_summary.md`, sitting right next to
`phase4_hybrid_gate4_summary.md` in the same directory, is not auto-
generated by anything — check `grep write_text experiments/*.py` before
assuming either way about a given `.md`).

Trajectories are **not** regenerated: spec §10, "Do not write results-
generating code that depends on network access at run time. Trajectories
are recorded once and committed." (`experiments/record_trajectories.py` is
that one-time tool, deliberately excluded from this pipeline — trajectories
are already committed under `trajectories/`.)

## Model choice per step

Each step's model matches how its currently-committed output was actually
produced, not a uniform default: Phase 0/1 predate the `--use-fallback`
decision (README's Environment section — introduced when Phase 2's
`append_only` policy exceeded the primary model's tight KV headroom) and
run on the primary model; every Phase 2+ step runs on the fallback model.
`gate0_check` and `phase1_cliff` below intentionally omit `--use-fallback`.

## Full run vs. `--smoke`

A full run replays every trajectory at every phase's real scale — many
hours of GPU time (Phase 4.5's sweep alone took multiple hours and hit
sustained GPU thermal throttling on this project's own hardware, documented
in `results/phase4/phase4_pareto_summary.md`). `--smoke` runs every step at
drastically reduced scale (1-2 trajectories, `--max-steps`/`--n-transactions`
capped hard) purely to verify the orchestration and CLI wiring end-to-end in
minutes — never treat `--smoke` output as a replacement for the real
committed results, and never commit files it produces over the real ones
(it writes the same filenames, so re-run a full pass afterward if you smoke-
tested against a real checkout).

Usage (inside the WSL venv):
    python experiments/run_all.py --dry-run       # print the plan, no GPU
    python experiments/run_all.py --smoke         # ~15-25 min, verifies wiring only
    python experiments/run_all.py                 # full reproduction, many hours
    python experiments/run_all.py --from phase4_pareto_cost   # resume from a step
    python experiments/run_all.py --only gate0_check           # run just one step
"""
