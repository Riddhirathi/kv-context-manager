def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--smoke", action="store_true", help="run every step at reduced scale")
    parser.add_argument("--dry-run", action="store_true", help="print the plan, run nothing")
    parser.add_argument("--from", dest="from_step", default=None, help="resume from this step")
    parser.add_argument("--only", dest="only_step", default=None, help="run just this one step")
    args = parser.parse_args()

    names = [s.name for s in STEPS]
    if args.only_step is not None:
        if args.only_step not in names:
            raise SystemExit(f"unknown step {args.only_step!r}; known steps: {names}")
        steps = [s for s in STEPS if s.name == args.only_step]
    elif args.from_step is not None:
        if args.from_step not in names:
            raise SystemExit(f"unknown step {args.from_step!r}; known steps: {names}")
        start = names.index(args.from_step)
        steps = STEPS[start:]
    else:
        steps = STEPS

    print(f"{'SMOKE' if args.smoke else 'FULL'} run, {len(steps)} step(s):")
    for step in steps:
        note = f"  ({step.note})" if step.note else ""
        print(f"  - {step.name}{note}")
    print()

    if args.dry_run:
        for step in steps:
            cmd_args = step.smoke_args if args.smoke else step.full_args
            print(f"$ python {' '.join(cmd_args)}")
        return

    total_start = time.monotonic()
    for i, step in enumerate(steps, start=1):
        cmd_args = step.smoke_args if args.smoke else step.full_args
        print(f"=== [{i}/{len(steps)}] {step.name} ===")
        print(f"$ python {' '.join(cmd_args)}")
        step_start = time.monotonic()
        result = subprocess.run(
            [sys.executable, *cmd_args], cwd=REPO_ROOT, check=False
        )
        elapsed = time.monotonic() - step_start
        if result.returncode != 0:
            raise SystemExit(
                f"step {step.name!r} failed (exit {result.returncode}) after {elapsed:.1f}s — "
                f"stopping. Resume with: python experiments/run_all.py --from {step.name}"
                f"{' --smoke' if args.smoke else ''}"
            )
        print(f"--- {step.name} done in {elapsed:.1f}s ---\n")

    total_elapsed = time.monotonic() - total_start
    print(f"All {len(steps)} step(s) completed in {total_elapsed / 60:.1f} min.")
    print(
        "Note: hand-authored narrative summaries (phaseN_summary.md, "
        "phase4_pareto_summary.md, phase6_demo_summary.md, "
        "results/demo_deck/rehearsal.md, etc.) are not regenerated by this "
        "script — see the module docstring's Scope section."
    )


if __name__ == "__main__":
    main()
